// Bitmap pixel fonts for Harvest Frenzy (full printable ASCII 32..126), drawn from glyph grids.
//
//   small  : 3x5 caps/digits (lowercase maps to uppercase, except 'x' = small multiply sign)
//            cap height 5, line height 7
//   normal : proportional 5x7 upper+lower case, cap height 7, x-height 5, descender 2, line height 11
//   big    : chunky bold 2px strokes, cap height 10, x-height 7, descender 3, line height 14
//
// Glyph data + layout (`FONTS`, `forEachTextPixel`) are DOM-free so they also work in Node tools.
// Rendering (`drawText`) builds a white atlas lazily with document.createElement('canvas'),
// caches tinted atlases per (font,color) and fully rendered strings per (text,font,colors).

export type FontName = 'small' | 'normal' | 'big';
export interface TextOpts {
  font?: FontName;
  color?: string;
  outline?: string | null;
  shadow?: string | null;
  align?: 'left' | 'center' | 'right';
}

export interface FontDef {
  /** glyph cell height in rows (includes descender area) */
  h: number;
  /** cap height (rows from top to baseline) */
  cap: number;
  /** blank pixels between glyphs */
  spacing: number;
  /** line advance */
  lineH: number;
  /** map lowercase letters to uppercase (small font) */
  upper?: boolean;
  glyphs: Record<string, string[]>;
}

